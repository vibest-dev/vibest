import { Effect, FileSystem, Path, Schema } from "effect"

export type JSONSchema = Record<string, any>

export const packagePath = (...segments: ReadonlyArray<string>) =>
  Effect.gen(function* () {
    const path = yield* Path.Path
    const here = path.dirname(yield* path.fromFileUrl(new URL(import.meta.url)))
    return path.join(here, "..", "..", ...segments)
  })

const decodeSchema = Schema.decodeUnknownEffect(Schema.fromJsonString(Schema.Record(Schema.String, Schema.Any)))

export const loadSchema = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const text = yield* fs.readFileString(yield* packagePath("schema", "herdr-api.schema.json"))
  return (yield* decodeSchema(text)) as JSONSchema
})

export function header(schema: JSONSchema): string {
  return `// GENERATED by scripts/gen from schema/herdr-api.schema.json — do not edit.\n// herdr protocol ${schema.protocol}, schema_version ${schema.schema_version}.\n`
}
