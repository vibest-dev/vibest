import { Effect, FileSystem, Path, Schema } from "effect"

export interface JSONSchema {
  readonly $ref?: string
  readonly const?: Schema.Json
  readonly enum?: ReadonlyArray<Schema.Json>
  readonly oneOf?: ReadonlyArray<JSONSchema>
  readonly anyOf?: ReadonlyArray<JSONSchema>
  readonly allOf?: ReadonlyArray<JSONSchema>
  readonly type?: string | ReadonlyArray<string>
  readonly properties?: { readonly [name: string]: JSONSchema | boolean }
  readonly required?: ReadonlyArray<string>
  readonly additionalProperties?: boolean | JSONSchema
  readonly items?: JSONSchema
  readonly description?: string
}

const Node: Schema.Codec<JSONSchema> = Schema.suspend(() => JSONSchema)

export const JSONSchema: Schema.Codec<JSONSchema> = Schema.Struct({
  $ref: Schema.optionalKey(Schema.String),
  const: Schema.optionalKey(Schema.Json),
  enum: Schema.optionalKey(Schema.Array(Schema.Json)),
  oneOf: Schema.optionalKey(Schema.Array(Node)),
  anyOf: Schema.optionalKey(Schema.Array(Node)),
  allOf: Schema.optionalKey(Schema.Array(Node)),
  type: Schema.optionalKey(Schema.Union([Schema.String, Schema.Array(Schema.String)])),
  properties: Schema.optionalKey(Schema.Record(Schema.String, Schema.Union([Node, Schema.Boolean]))),
  required: Schema.optionalKey(Schema.Array(Schema.String)),
  additionalProperties: Schema.optionalKey(Schema.Union([Schema.Boolean, Node])),
  items: Schema.optionalKey(Node),
  description: Schema.optionalKey(Schema.String),
})

export const Definitions = Schema.Record(Schema.String, JSONSchema)

const Namespace = Schema.Struct({ $defs: Definitions })

const Document = Schema.Struct({
  protocol: Schema.Number,
  schema_version: Schema.Number,
  schemas: Schema.Struct({
    request: Schema.Struct({ $defs: Definitions, oneOf: Schema.Array(JSONSchema) }),
    success_response: Namespace,
    error_response: Namespace,
    event: Namespace,
    subscription_event: Namespace,
  }),
})

export type Document = typeof Document.Type

export const packagePath = (...segments: ReadonlyArray<string>) =>
  Effect.gen(function* () {
    const path = yield* Path.Path
    const here = path.dirname(yield* path.fromFileUrl(new URL(import.meta.url)))

    return path.join(here, "..", "..", ...segments)
  })

const decodeDocument = Schema.decodeUnknownEffect(Schema.fromJsonString(Document))

export const loadSchema = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem

  return yield* decodeDocument(yield* fs.readFileString(yield* packagePath("schema", "herdr-api.schema.json")))
})

export function header(schema: Document): string {
  return `// GENERATED by scripts/gen from schema/herdr-api.schema.json — do not edit.\n// herdr protocol ${schema.protocol}, schema_version ${schema.schema_version}.\n`
}
